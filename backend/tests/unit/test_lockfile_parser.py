"""
Unit tests for Multi-Ecosystem Lockfile & Manifest Parsers.
Tests Go modules (go.mod), Rust crates (Cargo.lock & Cargo.toml),
and raw package.json fallback parsing with semver operator stripping.
"""

import pytest
from app.models.core import Ecosystem
from app.services.lockfile_parser import (
    LockfileParser,
    parse_go_mod,
    parse_cargo_lock,
    parse_cargo_toml,
    parse_package_json
)


class TestGoModParser:

    def test_parse_go_mod_basic_and_indirect(self):
        content = """
module my/awesome/app

go 1.21

require (
    github.com/gin-gonic/gin v1.9.1
    github.com/google/uuid v1.3.0
    golang.org/x/crypto v0.14.0 // indirect
    golang.org/x/net v0.17.0 // indirect; transitive network library
)

require github.com/sirupsen/logrus v1.9.3
require rsc.io/quote/v3 v3.1.0 // indirect
"""
        components = parse_go_mod(content)
        assert len(components) == 6

        # Check gin-gonic
        gin = next((c for c in components if c.name == "github.com/gin-gonic/gin"), None)
        assert gin is not None
        assert gin.version == "1.9.1"
        assert gin.ecosystem == Ecosystem.GOLANG
        assert gin.purl == "pkg:golang/github.com/gin-gonic/gin@1.9.1"
        assert gin.is_direct is True
        assert gin.is_transitive is False
        assert gin.depth == 1

        # Check indirect dependency golang.org/x/crypto
        crypto = next((c for c in components if c.name == "golang.org/x/crypto"), None)
        assert crypto is not None
        assert crypto.version == "0.14.0"
        assert crypto.ecosystem == Ecosystem.GOLANG
        assert crypto.purl == "pkg:golang/golang.org/x/crypto@0.14.0"
        assert crypto.is_direct is False
        assert crypto.is_transitive is True
        assert crypto.depth == 2

        # Check single-line direct require
        logrus = next((c for c in components if c.name == "github.com/sirupsen/logrus"), None)
        assert logrus is not None
        assert logrus.version == "1.9.3"
        assert logrus.is_direct is True

        # Check single-line indirect require
        quote = next((c for c in components if c.name == "rsc.io/quote/v3"), None)
        assert quote is not None
        assert quote.version == "3.1.0"
        assert quote.is_direct is False

    def test_parse_go_mod_empty_or_no_requires(self):
        content = "module example.com/standalone\n\ngo 1.20\n"
        components = parse_go_mod(content)
        assert components == []


class TestCargoParser:

    def test_parse_cargo_lock_package_tables(self):
        content = """
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "my-app"
version = "0.1.0"
dependencies = [
 "actix-web",
 "serde",
]

[[package]]
name = "actix-web"
version = "4.4.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0e48a803918df1fae13da9b8700b0682285d1b094e9f3cefcdfb0ca835550617"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "v1.0.193"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""
        components = parse_cargo_lock(content)
        assert len(components) >= 2

        actix = next((c for c in components if c.name == "actix-web"), None)
        assert actix is not None
        assert actix.version == "4.4.0"
        assert actix.ecosystem == Ecosystem.CARGO
        assert actix.purl == "pkg:cargo/actix-web@4.4.0"

        serde = next((c for c in components if c.name == "serde"), None)
        assert serde is not None
        assert serde.version == "1.0.193"  # Leading 'v' stripped
        assert serde.ecosystem == Ecosystem.CARGO
        assert serde.purl == "pkg:cargo/serde@1.0.193"

    def test_parse_cargo_toml_fallback(self):
        content = """
[package]
name = "rust-service"
version = "0.2.0"
edition = "2021"

[dependencies]
tokio = { version = "1.35.0", features = ["full"] }
serde = "^1.0.190"
actix-web = ">= 4.0.0"

[dev-dependencies]
criterion = "0.5.1"
"""
        components = parse_cargo_lock(content)  # Falls back to Cargo.toml parsing
        assert len(components) == 4

        tokio = next((c for c in components if c.name == "tokio"), None)
        assert tokio is not None
        assert tokio.version == "1.35.0"
        assert tokio.ecosystem == Ecosystem.CARGO
        assert tokio.is_direct is True

        serde = next((c for c in components if c.name == "serde"), None)
        assert serde is not None
        assert serde.version == "1.0.190"  # '^' stripped

        actix = next((c for c in components if c.name == "actix-web"), None)
        assert actix is not None
        assert actix.version == "4.0.0"  # '>=' stripped

        criterion = next((c for c in components if c.name == "criterion"), None)
        assert criterion is not None
        assert criterion.version == "0.5.1"
        assert criterion.is_direct is False  # dev-dependency


class TestPackageJsonFallback:

    def test_parse_package_json_semver_stripping(self):
        content = """{
  "name": "sample-npm-app",
  "version": "1.0.0",
  "dependencies": {
    "express": "^4.18.2",
    "@types/node": "~18.11.9",
    "react": ">=16.8.0",
    "lodash": "v4.17.21",
    "axios": "=1.2.0"
  },
  "devDependencies": {
    "jest": "^29.5.0",
    "@babel/core": "7.20.0"
  }
}"""
        components = parse_package_json(content)
        assert len(components) == 7

        # express
        exp = next((c for c in components if c.name == "express"), None)
        assert exp is not None
        assert exp.version == "4.18.2"
        assert exp.ecosystem == Ecosystem.NPM
        assert exp.purl == "pkg:npm/express@4.18.2"
        assert exp.is_direct is True

        # scoped package: @types/node
        types_node = next((c for c in components if c.name == "@types/node"), None)
        assert types_node is not None
        assert types_node.version == "18.11.9"
        assert types_node.ecosystem == Ecosystem.NPM
        assert types_node.purl == "pkg:npm/@types/node@18.11.9"

        # react: >=16.8.0
        react = next((c for c in components if c.name == "react"), None)
        assert react is not None
        assert react.version == "16.8.0"

        # lodash: v4.17.21
        lodash = next((c for c in components if c.name == "lodash"), None)
        assert lodash is not None
        assert lodash.version == "4.17.21"

        # axios: =1.2.0
        axios = next((c for c in components if c.name == "axios"), None)
        assert axios is not None
        assert axios.version == "1.2.0"

        # devDependencies: jest
        jest = next((c for c in components if c.name == "jest"), None)
        assert jest is not None
        assert jest.version == "29.5.0"
        assert jest.is_direct is False
        assert jest.is_dev is True

        # Check production-only filtering
        prod_only = [c for c in components if not getattr(c, "is_dev", False)]
        assert len(prod_only) == 5
        assert all(c.name not in ("jest", "@babel/core") for c in prod_only)


class TestLockfileParserRouter:

    def test_router_dispatches_by_filename(self):
        parser = LockfileParser()

        # go.mod
        go_content = "module test\nrequire github.com/gin-gonic/gin v1.9.1\n"
        go_comps = parser.parse_lockfile(go_content, "sub/dir/go.mod")
        assert len(go_comps) == 1
        assert go_comps[0].ecosystem == Ecosystem.GOLANG

        # Cargo.lock
        cargo_content = "[[package]]\nname = \"tokio\"\nversion = \"1.30.0\"\n"
        cargo_comps = parser.parse_lockfile(cargo_content, "Cargo.lock")
        assert len(cargo_comps) == 1
        assert cargo_comps[0].ecosystem == Ecosystem.CARGO

        # Cargo.toml
        toml_content = "[dependencies]\nserde = \"1.0.1\"\n"
        toml_comps = parser.parse_lockfile(toml_content, "Cargo.toml")
        assert len(toml_comps) == 1
        assert toml_comps[0].ecosystem == Ecosystem.CARGO

        # package.json
        pkg_json = '{"dependencies": {"express": "^4.18.0"}}'
        pkg_comps = parser.parse_lockfile(pkg_json, "package.json")
        assert len(pkg_comps) == 1
        assert pkg_comps[0].ecosystem == Ecosystem.NPM
        assert pkg_comps[0].version == "4.18.0"
